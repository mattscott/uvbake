using System.Globalization;
using System.Text;
using UVBake.Core.Geometry;
using UVBake.Core.Meshes;

namespace UVBake.IO;

/// <summary>
/// Writes a <see cref="Mesh"/> as Wavefront OBJ. Per-wedge UVs are emitted natively: a seam is a face
/// corner whose <c>vt</c> index differs from its neighbours' while the <c>v</c> index is shared, so no
/// vertex duplication is needed. Numbers are written invariant-culture and round-trippable; line endings
/// are LF (the repo stores OBJ as text). Smoothing groups are not re-emitted in this version.
/// </summary>
public static class ObjWriter
{
    /// <summary>Writes <paramref name="mesh"/> to <paramref name="path"/> as UTF-8 (no BOM), LF endings.</summary>
    public static void Write(Mesh mesh, string path)
    {
        ArgumentNullException.ThrowIfNull(mesh);
        ArgumentNullException.ThrowIfNull(path);
        using var writer = new StreamWriter(path, append: false, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        Write(mesh, writer);
    }

    /// <summary>Writes <paramref name="mesh"/> as OBJ text to <paramref name="writer"/> (LF endings).</summary>
    public static void Write(Mesh mesh, TextWriter writer)
    {
        ArgumentNullException.ThrowIfNull(mesh);
        ArgumentNullException.ThrowIfNull(writer);

        var sb = new StringBuilder();
        sb.Append("# generated by UVBake\n");

        foreach (Vector3 p in mesh.Positions)
        {
            sb.Append("v ").Append(Fmt(p.X)).Append(' ').Append(Fmt(p.Y)).Append(' ').Append(Fmt(p.Z)).Append('\n');
        }

        foreach (Vector2 uv in mesh.TexCoords)
        {
            sb.Append("vt ").Append(Fmt(uv.X)).Append(' ').Append(Fmt(uv.Y)).Append('\n');
        }

        foreach (Vector3 n in mesh.Normals)
        {
            sb.Append("vn ").Append(Fmt(n.X)).Append(' ').Append(Fmt(n.Y)).Append(' ').Append(Fmt(n.Z)).Append('\n');
        }

        foreach (Face face in mesh.Faces)
        {
            sb.Append('f');
            foreach (Corner corner in face.Corners)
            {
                sb.Append(' ');
                AppendCorner(sb, corner);
            }

            sb.Append('\n');
        }

        writer.Write(sb.ToString());
    }

    private static void AppendCorner(StringBuilder sb, Corner corner)
    {
        // OBJ indices are 1-based; emit v, v/vt, v//vn, or v/vt/vn to match which attributes are present.
        sb.Append((corner.Position + 1).ToString(CultureInfo.InvariantCulture));
        if (corner.HasTexCoord)
        {
            sb.Append('/').Append((corner.TexCoord + 1).ToString(CultureInfo.InvariantCulture));
            if (corner.HasNormal)
            {
                sb.Append('/').Append((corner.Normal + 1).ToString(CultureInfo.InvariantCulture));
            }
        }
        else if (corner.HasNormal)
        {
            sb.Append("//").Append((corner.Normal + 1).ToString(CultureInfo.InvariantCulture));
        }
    }

    /// <summary>Shortest round-trippable invariant-culture representation of a coordinate.</summary>
    private static string Fmt(double value) => value.ToString("R", CultureInfo.InvariantCulture);
}
